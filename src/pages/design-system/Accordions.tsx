const faqBehavior = `// Drupal behavior: toggle one row. Rows open independently.
Drupal.behaviors.usniAccordion = {
  attach(context) {
    once('usni-accordion', '.accordion-row', context).forEach((button) => {
      const panel = document.getElementById(button.getAttribute('aria-controls'))
      const item = button.closest('.faq-item')
      button.addEventListener('click', () => {
        const open = button.getAttribute('aria-expanded') !== 'true'
        button.setAttribute('aria-expanded', String(open))
        panel.hidden = !open
        item.classList.toggle('bg-white', open)
        button.querySelector('.accordion-chevron').classList.toggle('rotate-180', open)
      })
    })
  },
}`

