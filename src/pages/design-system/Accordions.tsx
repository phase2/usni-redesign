/**
 * The open state of one FAQ row. No FAQ section in the prototype accepts an
 * initial-open prop (each item keeps its own `useState(false)`), so this is
 * DonateFAQ's FAQItem markup with `open` fixed to true — the same classes, in
 * the same order, nothing added. Kept to the open branch only; the closed rows
 * beside it use the closed branch.
 */
function FaqItemStatic({ q, a, open }: { q: string; a: string; open: boolean }) {
  return (
    <div className={`border-b border-border-light last:border-b-0 transition-colors ${open ? 'bg-white' : ''}`}>
      <button className="accordion-row flex items-center justify-between w-full py-4 px-4 text-left gap-4" aria-expanded={open}>
        <span className="font-body font-semibold text-base text-navy-bolder">{q}</span>
        <span className={`accordion-chevron flex-shrink-0 w-8 h-8 bg-navy-bolder text-white flex items-center justify-center transition-transform duration-200 ${open ? 'rotate-180' : ''}`}>
          <svg className="w-4 h-4" viewBox="0 0 16 16" fill="none">
            <path d="M3 6l5 5 5-5" stroke="currentColor" strokeWidth="2" strokeLinecap="round" strokeLinejoin="round" />
          </svg>
        </span>
      </button>
      {open && (
        <div className="pt-4 pb-5 pl-4 pr-16">
          <p className="font-body text-base text-neutral-subtle leading-relaxed">{a}</p>
        </div>
      )}
    </div>
  )
}

