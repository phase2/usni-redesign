/**
 * The four annual recognition societies, with their donor courtesies and the
 * honour roll for each of the last five years.
 *
 * Transcribed from the four pages under /donate/annual-recognition-societies
 * on the live Drupal site (test-usni3.pantheonsite.io, captured 11 September
 * 2026). Each is the same Drupal shape: a courtesies list, then a tab per year
 * whose panel is one big table of names.
 *
 * Those tables are an alphabetical list split into columns — two for the first
 * three societies, three for the Leadership Circle — so the names here are
 * flattened column-major (all of column one, then column two) to recover the
 * single alphabetical run the tables were laid out from. The pages render that
 * run into CSS columns, which reflows to the reader's screen instead of being
 * frozen at the source's column count.
 *
 * Two exact duplicates in the source were dropped, both a name repeated inside
 * one year: "Navy Mutual Aid Association" (Mahan, 2024) and "ADM William F.
 * Moran, USN (Ret.)" (1873 Society, 2022). In each the later copy sits in
 * correct alphabetical position and the earlier one is a stray mid-column, so
 * the stray is the one dropped. Worth fixing in the CMS — they are data entry
 * errors, not two different donors.
 *
 * A trailing asterisk on a name marks a deceased donor. The footnote is derived
 * from the names rather than stored: the live pages carry it inconsistently
 * (the 1873 Society's 2022 tab prints the note with no starred name in the
 * list), so reading it off the data is the more reliable of the two.
 */

