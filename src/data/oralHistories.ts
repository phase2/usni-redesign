/**
 * Oral Histories — the Naval Institute Oral History Program's catalogue.
 *
 * Transcribed from /press/oral-histories on the live Drupal site
 * (test-usni3.pantheonsite.io, captured 7 October 2026): all 234 entries
 * across its twenty pages, with each card's name, life dates, teaser, and
 * portrait. The live listing is alphabetical with nothing else to go on; the
 * redesign files it under Archives and adds a keyword search, an A–Z row, and
 * sorting. `born` drives the date sort. `rank` and `service` were read for
 * Rank and Service facets that have since been taken off the listing; they
 * are kept in case the facets return.
 *
 * Generated from that capture rather than typed. Fields:
 * - `name` is the source title, as the live site sorts it ("Adair, Charles,
 *   Rear Adm., USN (Ret.)"). `title` is the surname-first name alone and
 *   `subtitle` the rank, service, and any descriptor after it, so a card can
 *   set the two at different weights.
 * - `dates` holds life dates where the source gave years. A few entries use
 *   that field for something else — a list of interviewees, "Volumes I and
 *   II" — and that text is kept as `note` instead.
 * - `born` is the first year in `dates`, for sorting by birth year. Living
 *   subjects carry an open range ("1946–").
 * - `rank` is a coarse grouping read from the title (flag officers; captains
 *   and commanders; enlisted and warrant officers; civilians; group
 *   histories). Entries the title gives no rank for — most of the Golden
 *   Thirteen, several veterans' recollections — are left out of it rather
 *   than guessed.
 * - `service` is read the same way, from USN/USNR, USCG/USCGR, USAF, USMS.
 * - `summary` is the live teaser, which the site cuts at about 300
 *   characters; its trailing "..." is kept as an ellipsis.
 *
 * NOTE for USNI — titles corrected from the live source, worth fixing there:
 * Coughlin, Moorer, and Read were missing a comma or had the rank inside the
 * name; Gayler read "Adm.Noel"; Waters read "Odale D., Jr. Rear Adm.";
 * Andrew McBurney Jackson Jr. was missing the comma before USN; Paul J. Reason
 * was missing the period after his initial; William T. Smoot was spelled
 * "WIlliam"; and Miller, Owens, and Reason were "ADM." in capitals.
 *
 * Detail pages (/archives/oral-histories/<slug>) are not built in the
 * prototype; cards link to where they would live.
 */

const images = import.meta.glob('../assets/images/oral-histories/*', {
  eager: true,
  query: '?url',
  import: 'default',
}) as Record<string, string>

/** Resolve an entry's portrait filename to its bundled URL. */
export function oralHistoryImage(file: string): string | undefined {
  return images[`../assets/images/oral-histories/${file}`]
}

export type OralHistoryRank =
  | 'Flag officers'
  | 'Captains & commanders'
  | 'Enlisted & warrant officers'
  | 'Civilians'
  | 'Group histories'

export type OralHistoryService = 'Navy' | 'Coast Guard' | 'Air Force' | 'Maritime Service'

export interface OralHistory {
  slug: string
  /** The full source title, surname first. */
  name: string
  /** "Surname, Given" — or the whole title, for a group history. */
  title: string
  /** Rank, service, and descriptor: everything in `name` after `title`. */
  subtitle?: string
  /** Life dates, e.g. "1902–1993". */
  dates?: string
  /** What the source put in the dates field when it was not dates. */
  note?: string
  born?: number
  rank?: OralHistoryRank
  service?: OralHistoryService
  summary: string
  image: string
  imageAlt: string
}

/** Where an entry's page would live. */
export const oralHistoryHref = (h: OralHistory) => `/archives/oral-histories/${h.slug}`

