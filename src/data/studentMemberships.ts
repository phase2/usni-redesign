/**
 * Sponsor Student Memberships — the intro, the regional totals, and the
 * directory of every unit the Foundation is raising gratis memberships for.
 *
 * Transcribed from /donate/student-memberships on the live Drupal site
 * (test-usni3.pantheonsite.io, captured 11 September 2026): 77 schools across
 * five regions, with their NROTC seals, sponsorship counts, consortium notes,
 * and named donors. The two academies carry sub-units — eight Coast Guard
 * Academy companies and thirty Naval Academy companies — which the live page
 * nests under their school.
 *
 * `logo` is a filename in `assets/images/school-logos/`, named by school slug
 * and resolved through the glob in `schoolLogo()`. The source seals run to
 * 53 MB at full size; they render at roughly 80px here, so they are stored
 * resized.
 *
 * The live page offers Region and State filters, but state is a filter-only
 * field — it appears in no school record — so the directory filters by region
 * and by a name search instead, which is what the cards can actually answer.
 */

const logos = import.meta.glob('../assets/images/school-logos/*', {
  eager: true,
  query: '?url',
  import: 'default',
}) as Record<string, string>

/** Resolve a school slug to its bundled seal. */
export function schoolLogo(file?: string): string | undefined {
  if (!file) return undefined
  return logos[`../assets/images/school-logos/${file}`]
}

export interface SchoolUnit {
  name: string
  members: number
  needed: number
  donors: string[]
}

export interface School {
  slug: string
  name: string
  region: string
  logo?: string
  members: number
  needed: number
  /** Consortium or programme note the live card carries under the counts. */
  note?: string
  donors: string[]
  /** Companies within an academy, as the live page nests them. */
  units: SchoolUnit[]
}

